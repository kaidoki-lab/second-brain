_TABLE = {c: ([date.fromisoformat(d) for d, _ in v], [r for _, r in v]) for c, v in _RAW.items()}
CURRENCIES = tuple(_RAW)
SINCE = date(2008, 1, 1)   # no rates before this: swap counts as 0 and carry (side=0) stays out


def covered(day: date) -> bool:
    return day >= SINCE


def _pair(symbol: str) -> tuple[str, str]:
    """'USDJPY-' / 'usdjpy.m' -> ('USD', 'JPY')."""
    letters = "".join(ch for ch in symbol.upper() if ch.isalpha())[:6]
    base, quote = letters[:3], letters[3:6]
    if base not in _TABLE or quote not in _TABLE:
        raise ValueError(f"{symbol!r} の金利が金利表にありません (使える通貨: {', '.join(CURRENCIES)})")
    return base, quote


def rate(ccy: str, day: date) -> float:
    days, vals = _TABLE[ccy]
    return vals[max(bisect_right(days, day) - 1, 0)]


def diff(symbol: str, day: date) -> float:
    """Yearly % a long position earns before the broker's cut (base rate - quote rate)."""
    base, quote = _pair(symbol)
    return rate(base, day) - rate(quote, day)


def estimator(symbol: str, cut: float = 1.0) -> Callable[[datetime], tuple[float, float]]:
    """time -> (long %, short %) per year after the broker's `cut`; negative means the side pays."""
    _pair(symbol)

    def at(when: datetime) -> tuple[float, float]:
        if not covered(when.date()):
            return 0.0, 0.0
        d = diff(symbol, when.date())
        return d - cut, -d - cut
    return at
